            fn validate_until(
                wire: &pbrs::rt::Wire,
                pos: &mut usize,
                depth: u32,
                until: Option<u32>,
            ) -> Result<(), ParseError> {
                if depth > pbrs::RECURSION_LIMIT {
                    return Err(ParseError::new("recursion limit exceeded"));
                }
                let data = wire.as_slice();
                while *pos < data.len() {
                    let (n, w) = pbrs::rt::decode_tag(data, pos)?;
                    if let Some(g) = until {
                        if w == pbrs::rt::WIRE_EGROUP {
                            if n != g {
                                return Err(ParseError::new("mismatched end-group"));
                            }
                            return Ok(());
                        }
                    }
                    match n {
                        1 => match w {
                            pbrs::rt::WIRE_LEN => {
                                let (s, e) = pbrs::rt::read_len_span(data, pos)?;
                                pbrs::rt::require_utf8(&data[s..e])?;
                            }
                            _ => pbrs::rt::skip_field(data, pos, w)?,
                        },
                        _ => pbrs::rt::skip_field(data, pos, w)?,
                    }
                }
                if until.is_some() {
                    return Err(ParseError::new("truncated group"));
                }
                Ok(())
            }
