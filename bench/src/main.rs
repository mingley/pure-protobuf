/// Cases whose wire bytes are byte-stable across encoders. Multi-entry maps
/// (`tat_populated`, `map_64`) serialize in encoder-defined order, so those
/// cases get cross-parse checks instead of byte equality.
fn byte_stable(name: &str) -> bool {
    !matches!(name, "tat_populated" | "map_64")
}

/// Holdout topology label for per-case reporting (see docs/benchmarks.md).
fn topology(name: &str) -> &'static str {
    match name {
        "empty" => "sparse-wide",
        "person" | "person_generated" => "small-struct",
        "tat_populated" => "kitchen-sink",
        "packed_256" => "packed-varint",
        "map_64" => "wide-map",
        "nested_8" => "deep-tree",
        "strings" => "text-heavy",
        "unpacked_256" => "unpacked-varint",
        "packed_fixed_256" | "packed_fixed64_256" | "packed_float_256" => "packed-fixed",
        "bytes" => "bytes-blob",
        "scalars" => "scalar-pack",
        "unpacked_fixed_256" => "unpacked-fixed",
        "oneof" => "union",
        "repeated_nested_8" => "repeated-nested",
        "bytes_1mb" | "bytes_5mb" => "large-blob",
        "packed_fixed_1mb" | "packed_fixed_5mb" => "large-packed-fixed",
        _ => "other",
    }
}

