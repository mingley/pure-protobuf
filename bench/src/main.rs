            fn compute_size(&self) -> u64 {
                if let Some(n) = self.cached_size.get() {
                    return n;
                }
                let mut n = self.unknown.encoded_len();
                if self.id != 0 {
                    n += pbrs::rt::tag_len(1, pbrs::rt::WIRE_VARINT)
                        + pbrs::rt::varint_len((self.id) as u64);
                }
                if let Some(c) = self.cold.as_deref() {
                    if !c.name.is_empty() {
                        n += pbrs::rt::key_len_value_len(2, c.name.as_bytes().len() as u64);
                    }
                    if let Some(s) = &c.email {
                        n += pbrs::rt::key_len_value_len(3, s.as_bytes().len() as u64);
                    }
                    for t in c.tags.iter() {
                        n += pbrs::rt::key_len_value_len(4, t.as_bytes().len() as u64);
                    }
                    if !c.scores.is_empty() {
                        for (k, v) in c.scores.pairs() {
                            let inner = pbrs::rt::key_len_value_len(1, k.as_bytes().len() as u64)
                                + pbrs::rt::tag_len(2, pbrs::rt::WIRE_VARINT)
                                + pbrs::rt::varint_len((*v) as u64);
                            n += pbrs::rt::key_len_value_len(5, inner);
                        }
                    }
                    if let Some(p) = c.address.wire_bytes() {
                        n += pbrs::rt::key_len_value_len(6, p.len() as u64);
                    } else if let Some(m) = c.address.as_deref() {
                        n += pbrs::rt::key_len_value_len(6, m.compute_size());
                    }
                    if !c.extras.is_empty() {
                        for (k, v) in c.extras.pairs() {
                            let inner = pbrs::rt::key_len_value_len(1, k.as_bytes().len() as u64)
                                + pbrs::rt::tag_len(2, pbrs::rt::WIRE_VARINT)
                                + pbrs::rt::varint_len((*v) as u64);
                            n += pbrs::rt::key_len_value_len(16, inner);
                        }
                    }
                }
                self.cached_size.set(n);
                n
            }
            fn write_to(&self, out: &mut impl pbrs::rt::WireOut) {
                if self.id != 0 {
                    pbrs::rt::encode_tag(out, 1, pbrs::rt::WIRE_VARINT);
                    pbrs::rt::encode_varint(out, self.id as u64);
                }
                if let Some(c) = self.cold.as_deref() {
                    if !c.name.is_empty() {
                        pbrs::rt::encode_len_field(out, 2, c.name.as_bytes());
                    }
                    if let Some(s) = &c.email {
                        pbrs::rt::encode_len_field(out, 3, s.as_bytes());
                    }
                    for t in c.tags.iter() {
                        pbrs::rt::encode_len_field(out, 4, t.as_bytes());
                    }
                    if !c.scores.is_empty() {
                        for (k, v) in c.scores.pairs() {
                            let inner = pbrs::rt::key_len_value_len(1, k.as_bytes().len() as u64)
                                + pbrs::rt::tag_len(2, pbrs::rt::WIRE_VARINT)
                                + pbrs::rt::varint_len((*v) as u64);
                            pbrs::rt::encode_tag(out, 5, pbrs::rt::WIRE_LEN);
                            pbrs::rt::encode_varint(out, inner);
                            pbrs::rt::encode_len_field(out, 1, k.as_bytes());
                            pbrs::rt::encode_tag(out, 2, pbrs::rt::WIRE_VARINT);
                            pbrs::rt::encode_varint(out, *v as u64);
                        }
                    }
                    if let Some(p) = c.address.wire_bytes() {
                        pbrs::rt::encode_len_header(out, 6, p.len() as u64);
                        out.extend_from_slice(p);
                    } else if let Some(m) = c.address.as_deref() {
                        pbrs::rt::encode_len_header(out, 6, m.compute_size());
                        m.write_to(out);
                    }
                    if !c.extras.is_empty() {
                        for (k, v) in c.extras.pairs() {
                            let inner = pbrs::rt::key_len_value_len(1, k.as_bytes().len() as u64)
                                + pbrs::rt::tag_len(2, pbrs::rt::WIRE_VARINT)
                                + pbrs::rt::varint_len((*v) as u64);
                            pbrs::rt::encode_tag(out, 16, pbrs::rt::WIRE_LEN);
                            pbrs::rt::encode_varint(out, inner);
                            pbrs::rt::encode_len_field(out, 1, k.as_bytes());
                            pbrs::rt::encode_tag(out, 2, pbrs::rt::WIRE_VARINT);
                            pbrs::rt::encode_varint(out, *v as u64);
                        }
                    }
                }
                self.unknown.encode(out);
            }
