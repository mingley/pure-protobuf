            fn merge_inner(
                &mut self,
                data: &[u8],
                wire: &mut Option<pbrs::rt::Wire>,
                pos: &mut usize,
                depth: u32,
                enforce: bool,
                until: Option<u32>,
            ) -> Result<(), ParseError> {
                if depth > pbrs::RECURSION_LIMIT {
                    return Err(ParseError::new("recursion limit exceeded"));
                }
                let _ = enforce;
                self.cached_size.dirty();
                while *pos < data.len() {
                    let (n, w) = pbrs::rt::decode_tag(data, pos)?;
                    if let Some(g) = until {
                        if w == pbrs::rt::WIRE_EGROUP {
                            if n != g {
                                return Err(ParseError::new("mismatched end-group"));
                            }
                            return Ok(());
                        }
                    }
                    if n == 1 {
                        match w {
                            pbrs::rt::WIRE_VARINT => {
                                self.id = pbrs::rt::decode_varint(data, pos)? as i32;
                            }
                            _ => self
                                .unknown
                                .fields
                                .push(pbrs::rt::capture_unknown(data, pos, n, w)?),
                        }
                        continue;
                    }
                    self.merge_heavy(n, w, data, wire, pos, depth)?;
                }
                if until.is_some() {
                    return Err(ParseError::new("truncated group"));
                }
                if enforce {
                    self.check_required()?;
                }
                Ok(())
            }
