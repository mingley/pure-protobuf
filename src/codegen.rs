//! Generate typed Rust accessors wrapping DynamicMessage (not Google upb gencode).

use crate::dynamic::{
    Cardinality, DescriptorPool, FieldDescriptor, FieldType, MessageDescriptor, Presence,
};
use crate::error::ParseError;
use crate::wire::{self, decode_tag, encode_len_field, encode_varint, read_len_bytes, WIRE_LEN};
use std::fmt::Write as _;

pub fn generate_from_code_generator_request(
    bytes: &[u8],
) -> Result<Vec<(String, String)>, ParseError> {
    let mut files_to_generate = Vec::new();
    let mut proto_files = Vec::new();
    let mut pos = 0;
    while pos < bytes.len() {
        let (n, w) = decode_tag(bytes, &mut pos)?;
        match (n, w) {
            (1, WIRE_LEN) => {
                let s = read_len_bytes(bytes, &mut pos)?;
                files_to_generate.push(String::from_utf8_lossy(s).into_owned());
            }
            (15, WIRE_LEN) => {
                let blob = read_len_bytes(bytes, &mut pos)?.to_vec();
                proto_files.push(blob);
            }
            _ => wire::skip_field(bytes, &mut pos, w)?,
        }
    }
    let mut fds = Vec::new();
    for blob in &proto_files {
        encode_len_field(&mut fds, 1, blob);
    }
    let pool = DescriptorPool::from_file_descriptor_set(&fds)?;
    let wanted: std::collections::BTreeSet<String> = files_to_generate.iter().cloned().collect();
    let names: Vec<String> = pool.collect_names();
    let mut src = String::from(
        "// @generated by protoc-gen-pure-protobuf\n#![allow(dead_code, unused_imports, clippy::all)]\nuse protobuf::prelude::*;\nuse protobuf::{Map, ParseError, ProtoBytes, ProtoString, Repeated, SerializeError};\n\n",
    );
    emit_fds(&mut src, &fds);
    src.push_str(
        "fn generated_pool() -> std::sync::Arc<protobuf::DescriptorPool> {\n    static P: std::sync::OnceLock<std::sync::Arc<protobuf::DescriptorPool>> = std::sync::OnceLock::new();\n    P.get_or_init(|| {\n        std::sync::Arc::new(protobuf::DescriptorPool::from_file_descriptor_set(FILE_DESCRIPTOR_SET).expect(\"fds\"))\n    }).clone()\n}\n\n",
    );
    for name in names {
        let Some(desc) = pool.get_message(&name) else {
            continue;
        };
        if desc.is_map_entry {
            continue;
        }
        if !wanted.is_empty()
            && !file_matches(&wanted, &desc.file_name)
            && !desc.full_name.starts_with("google.protobuf.")
        {
            continue;
        }
        emit_message(&mut src, &desc);
    }
    let filename = files_to_generate
        .first()
        .map(|f| {
            let stem = std::path::Path::new(f)
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("generated");
            format!("{stem}.rs")
        })
        .unwrap_or_else(|| "generated.rs".into());
    Ok(vec![(filename, src)])
}

pub fn encode_code_generator_response(files: &[(String, String)]) -> Vec<u8> {
    let mut out = Vec::new();
    encode_varint_field(&mut out, 2, 1);
    for (name, content) in files {
        let mut file = Vec::new();
        encode_string_field(&mut file, 1, name);
        encode_string_field(&mut file, 15, content);
        encode_len_field(&mut out, 15, &file);
    }
    out
}

fn file_matches(wanted: &std::collections::BTreeSet<String>, file_name: &str) -> bool {
    if file_name.is_empty() {
        return true;
    }
    let file_stem = std::path::Path::new(file_name)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or(file_name);
    wanted.iter().any(|w| {
        let w_stem = std::path::Path::new(w)
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or(w);
        w == file_name
            || w.ends_with(file_name)
            || file_name.ends_with(w)
            || w_stem == file_stem
            || w.contains(file_stem)
            || file_name.contains(w_stem)
    })
}

fn emit_fds(src: &mut String, fds: &[u8]) {
    src.push_str("const FILE_DESCRIPTOR_SET: &[u8] = &[\n");
    for (i, b) in fds.iter().enumerate() {
        if i % 16 == 0 {
            src.push_str("    ");
        }
        let _ = write!(src, "0x{b:02x},");
        if i % 16 == 15 {
            src.push('\n');
        }
    }
    if fds.len() % 16 != 0 {
        src.push('\n');
    }
    src.push_str("];\n\n");
}

fn encode_varint_field(out: &mut Vec<u8>, n: u32, v: u64) {
    crate::wire::encode_tag(out, n, crate::wire::WIRE_VARINT);
    encode_varint(out, v);
}

fn encode_string_field(out: &mut Vec<u8>, n: u32, s: &str) {
    encode_len_field(out, n, s.as_bytes());
}

fn rust_ident(s: &str) -> String {
    let last = s.rsplit('.').next().unwrap_or(s);
    let mut id = String::new();
    for (i, c) in last.chars().enumerate() {
        if c.is_ascii_alphanumeric() || c == '_' {
            id.push(c);
        } else if i > 0 {
            id.push('_');
        }
    }
    if id.is_empty() {
        id.push('M');
    }
    if matches!(
        id.as_str(),
        "type" | "match" | "self" | "super" | "crate" | "mod" | "fn" | "let" | "mut" | "pub"
    ) {
        return format!("r#{id}");
    }
    if matches!(
        id.as_str(),
        "Value" | "Option" | "Result" | "Vec" | "String" | "Box" | "Type"
    ) {
        if let Some(parent) = s.rsplit('.').nth(1) {
            let mut p: String = parent
                .chars()
                .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
                .collect();
            if !p.is_empty() {
                if let Some(s) = p.get_mut(0..1) {
                    s.make_ascii_uppercase();
                }
                return format!("{p}{id}");
            }
        }
        return format!("Pb{id}");
    }
    id
}

fn scalar_type(field: &FieldDescriptor) -> String {
    match field.field_type {
        FieldType::Double => "f64".into(),
        FieldType::Float => "f32".into(),
        FieldType::Int64 | FieldType::Sint64 | FieldType::Sfixed64 => "i64".into(),
        FieldType::Int32 | FieldType::Sint32 | FieldType::Sfixed32 | FieldType::Enum => {
            "i32".into()
        }
        FieldType::Uint64 | FieldType::Fixed64 => "u64".into(),
        FieldType::Uint32 | FieldType::Fixed32 => "u32".into(),
        FieldType::Bool => "bool".into(),
        FieldType::String => "ProtoString".into(),
        FieldType::Bytes => "ProtoBytes".into(),
        FieldType::Message | FieldType::Group => rust_ident(
            field
                .type_name
                .as_deref()
                .or_else(|| field.message.as_ref().map(|m| m.full_name.as_str()))
                .unwrap_or("UnknownMsg"),
        ),
    }
}

fn map_kv(field: &FieldDescriptor) -> (String, String) {
    let entry = field.message.as_ref();
    let k = entry
        .and_then(|e| e.field(1))
        .map(scalar_type)
        .unwrap_or_else(|| "ProtoString".into());
    let v = entry
        .and_then(|e| e.field(2))
        .map(scalar_type)
        .unwrap_or_else(|| "i32".into());
    (k, v)
}

fn is_option(field: &FieldDescriptor) -> bool {
    !field.is_map
        && field.cardinality != Cardinality::Repeated
        && (field.field_type == FieldType::Message
            || field.field_type == FieldType::Group
            || field.presence == Presence::Explicit)
}

fn emit_message(src: &mut String, desc: &MessageDescriptor) {
    let name = rust_ident(&desc.full_name);
    let view = format!("{name}View");
    let mut_ = format!("{name}Mut");
    let _ = writeln!(
        src,
        "protobuf::impl_generated_message!({name}, {view}, {mut_}, \"{}\", generated_pool());",
        desc.full_name
    );
    let _ = writeln!(src, "impl {name} {{");
    for f in desc.fields.values() {
        emit_accessors(src, f);
    }
    let _ = writeln!(src, "}}");
}

fn emit_accessors(src: &mut String, f: &FieldDescriptor) {
    let id = rust_ident(&f.name);
    let num = f.number;
    if f.is_map {
        let (k, v) = map_kv(f);
        let _ = writeln!(
            src,
            "    pub fn {id}(&self) -> Map<{k}, {v}> {{ protobuf::gen_support::map_from(self.inner.get_map({num})) }}"
        );
        let _ = writeln!(
            src,
            "    pub fn {id}_mut(&mut self) -> protobuf::gen_support::DynMapMut<'_, {k}, {v}> {{ protobuf::gen_support::DynMapMut {{ msg: &mut self.inner, number: {num}, _k: std::marker::PhantomData, _v: std::marker::PhantomData }} }}"
        );
        let _ = writeln!(
            src,
            "    pub fn set_{id}(&mut self, v: Map<{k}, {v}>) {{ self.inner.clear_field({num}); for (k, val) in v.iter() {{ self.inner.insert_map({num}, protobuf::gen_support::IntoMapKey::into_map_key(k.clone()), protobuf::gen_support::IntoFieldValue::into_field_value(val.clone())); }} }}"
        );
        return;
    }
    if f.cardinality == Cardinality::Repeated {
        let t = scalar_type(f);
        let _ = writeln!(
            src,
            "    pub fn {id}(&self) -> Repeated<{t}> {{ protobuf::gen_support::repeated_from(self.inner.get_repeated({num})) }}"
        );
        let _ = writeln!(
            src,
            "    pub fn {id}_mut(&mut self) -> protobuf::gen_support::DynRepeatedMut<'_, {t}> {{ protobuf::gen_support::DynRepeatedMut {{ msg: &mut self.inner, number: {num}, _v: std::marker::PhantomData }} }}"
        );
        return;
    }
    if f.field_type == FieldType::Message || f.field_type == FieldType::Group {
        let t = scalar_type(f);
        let _ = writeln!(
            src,
            "    pub fn has_{id}(&self) -> bool {{ self.inner.has({num}) }}"
        );
        let _ = writeln!(
            src,
            "    pub fn {id}(&self) -> Option<{t}> {{ match self.inner.get_singular({num}) {{ Some(protobuf::Value::Message(m)) => Some({t}::from_dynamic(m.clone())), _ => None }} }}"
        );
        let _ = writeln!(
            src,
            "    pub fn set_{id}(&mut self, v: {t}) {{ self.inner.set({num}, protobuf::Value::Message(v.into_dynamic())); }}"
        );
        let _ = writeln!(
            src,
            "    pub fn clear_{id}(&mut self) {{ self.inner.clear_field({num}); }}"
        );
        return;
    }
    if f.field_type == FieldType::String {
        if is_option(f) {
            let _ = writeln!(
                src,
                "    pub fn has_{id}(&self) -> bool {{ self.inner.has({num}) }}"
            );
        }
        let _ = writeln!(
            src,
            "    pub fn {id}(&self) -> &protobuf::ProtoStr {{ protobuf::gen_support::str_from(self.inner.get_singular({num})) }}"
        );
        let _ = writeln!(
            src,
            "    pub fn set_{id}(&mut self, v: impl protobuf::IntoProxied<ProtoString>) {{ self.inner.set({num}, protobuf::Value::String(v.into_proxied())); }}"
        );
        if is_option(f) {
            let _ = writeln!(
                src,
                "    pub fn clear_{id}(&mut self) {{ self.inner.clear_field({num}); }}"
            );
        }
        return;
    }
    if f.field_type == FieldType::Bytes {
        let _ = writeln!(
            src,
            "    pub fn {id}(&self) -> &[u8] {{ protobuf::gen_support::bytes_from(self.inner.get_singular({num})) }}"
        );
        let _ = writeln!(
            src,
            "    pub fn set_{id}(&mut self, v: impl protobuf::IntoProxied<ProtoBytes>) {{ self.inner.set({num}, protobuf::Value::Bytes(v.into_proxied())); }}"
        );
        return;
    }
    let getter = match f.field_type {
        FieldType::Double => "f64_from",
        FieldType::Float => "f32_from",
        FieldType::Int64 | FieldType::Sint64 | FieldType::Sfixed64 => "i64_from",
        FieldType::Uint64 | FieldType::Fixed64 => "u64_from",
        FieldType::Uint32 | FieldType::Fixed32 => "u32_from",
        FieldType::Bool => "bool_from",
        _ => "i32_from",
    };
    let t = scalar_type(f);
    let value_ctor = match f.field_type {
        FieldType::Double => "Double",
        FieldType::Float => "Float",
        FieldType::Int64 | FieldType::Sint64 | FieldType::Sfixed64 => "Int64",
        FieldType::Uint64 | FieldType::Fixed64 => "Uint64",
        FieldType::Uint32 | FieldType::Fixed32 => "Uint32",
        FieldType::Bool => "Bool",
        FieldType::Enum => "Enum",
        _ => "Int32",
    };
    let _ = writeln!(
        src,
        "    pub fn {id}(&self) -> {t} {{ protobuf::gen_support::{getter}(self.inner.get_singular({num})) }}"
    );
    let _ = writeln!(
        src,
        "    pub fn set_{id}(&mut self, v: {t}) {{ self.inner.set({num}, protobuf::Value::{value_ctor}(v)); }}"
    );
}
