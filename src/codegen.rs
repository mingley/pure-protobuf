fn enum_supports_typed(f: &FieldDescriptor) -> bool {
    let Some(en) = f.enum_ty.as_ref() else {
        return false;
    };
    if en.closed {
        return false;
    }
    !en.full_name
        .trim_start_matches('.')
        .starts_with("google.protobuf.")
}

fn message_type_name(f: &FieldDescriptor) -> &str {
    f.type_name
        .as_deref()
        .or_else(|| f.message.as_ref().map(|m| m.full_name.as_str()))
        .unwrap_or("")
        .trim_start_matches('.')
}

