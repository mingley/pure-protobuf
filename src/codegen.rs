fn wire_const(ty: FieldType) -> &'static str {
    match ty {
        FieldType::Fixed64 | FieldType::Sfixed64 | FieldType::Double => "pbrs::rt::WIRE_I64",
        FieldType::Fixed32 | FieldType::Sfixed32 | FieldType::Float => "pbrs::rt::WIRE_I32",
        FieldType::String | FieldType::Bytes | FieldType::Message | FieldType::Group => {
            "pbrs::rt::WIRE_LEN"
        }
        _ => "pbrs::rt::WIRE_VARINT",
    }
}

fn implicit_present(path: &str, ty: FieldType) -> String {
    match ty {
        FieldType::Bool => path.to_string(),
        FieldType::Float | FieldType::Double => format!("{path}.to_bits() != 0"),
        FieldType::String | FieldType::Bytes => format!("!{path}.is_empty()"),
        _ => format!("{path} != 0"),
    }
}

fn map_key_ty(field: &FieldDescriptor) -> FieldType {
    field
        .message
        .as_ref()
        .and_then(|e| e.field(1))
        .map(|f| f.field_type)
        .unwrap_or(FieldType::String)
}

fn map_val_ty(field: &FieldDescriptor) -> FieldType {
    field
        .message
        .as_ref()
        .and_then(|e| e.field(2))
        .map(|f| f.field_type)
        .unwrap_or(FieldType::Int32)
}

fn emit_codec(src: &mut String, desc: &MessageDescriptor) {
    let required: Vec<_> = desc
        .fields
        .values()
        .filter(|f| f.cardinality == Cardinality::Required)
        .collect();
    let _ = writeln!(
        src,
        "    #[inline(always)] fn check_required(&self) -> Result<(), ParseError> {{"
    );
    for f in &required {
        let id = field_id(f);
        if is_option(f) {
            let _ = writeln!(
                src,
                "        if self.{id}.is_none() {{ return Err(ParseError::new(\"missing required field\")); }}"
            );
        }
    }
    let _ = writeln!(src, "        Ok(())");
    let _ = writeln!(src, "    }}");
    let _ = writeln!(
        src,
        "    fn merge_bytes(&mut self, data: &[u8], depth: u32) -> Result<(), ParseError> {{ if data.is_empty() {{ return self.check_required(); }} let mut pos = 0; let mut wire = None; self.merge_inner(data, &mut wire, &mut pos, depth, true, None) }}"
    );
    let _ = writeln!(
        src,
        "    fn merge_bytes_dont_enforce(&mut self, data: &[u8], depth: u32) -> Result<(), ParseError> {{ if data.is_empty() {{ return Ok(()); }} let mut pos = 0; let mut wire = None; self.merge_inner(data, &mut wire, &mut pos, depth, false, None) }}"
    );
    let _ = writeln!(
        src,
        "    fn merge_group(&mut self, data: &[u8], wire: &mut Option<pbrs::rt::Wire>, pos: &mut usize, num: u32, depth: u32) -> Result<(), ParseError> {{ self.merge_inner(data, wire, pos, depth, false, Some(num)) }}"
    );
    let _ = writeln!(
        src,
        "    fn merge_inner(&mut self, data: &[u8], wire: &mut Option<pbrs::rt::Wire>, pos: &mut usize, depth: u32, enforce: bool, until: Option<u32>) -> Result<(), ParseError> {{"
    );
    let _ = writeln!(
        src,
        "        if depth > pbrs::RECURSION_LIMIT {{ return Err(ParseError::new(\"recursion limit exceeded\")); }} let _ = enforce;"
    );
    let _ = writeln!(src, "        self.cached_size.dirty();");
    let lights: Vec<_> = desc
        .fields
        .values()
        .filter(|f| is_light_merge_field(f))
        .collect();
    let heavies: Vec<_> = desc
        .fields
        .values()
        .filter(|f| !is_light_merge_field(f))
        .collect();
    let split_heavy =
        !desc.message_set_wire_format && (1..=4).contains(&lights.len()) && !heavies.is_empty();
    let _ = writeln!(src, "        while *pos < data.len() {{");
    let _ = writeln!(
        src,
        "            let (n, w) = pbrs::rt::decode_tag(data, pos)?;"
    );
    let _ = writeln!(src, "            if let Some(g) = until {{ if w == pbrs::rt::WIRE_EGROUP {{ if n != g {{ return Err(ParseError::new(\"mismatched end-group\")); }} return Ok(()); }} }}");
    if split_heavy {
        for f in &lights {
            let _ = writeln!(src, "            if n == {} {{", f.number);
            let _ = writeln!(src, "                match w {{");
            emit_merge_arm(src, desc, f);
            let _ = writeln!(
                src,
                "                    _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
            );
            let _ = writeln!(src, "                }}");
            let _ = writeln!(src, "                continue;");
            let _ = writeln!(src, "            }}");
        }
        let _ = writeln!(
            src,
            "            self.merge_heavy(n, w, data, wire, pos, depth)?;"
        );
    } else {
        let _ = writeln!(src, "            match n {{");
        if desc.message_set_wire_format {
            emit_message_set_merge(src, desc);
        }
        for f in desc.fields.values() {
            if desc.message_set_wire_format && f.number == 1 {
                continue;
            }
            let _ = writeln!(src, "            {} => match w {{", f.number);
            emit_merge_arm(src, desc, f);
            let _ = writeln!(
                src,
                "                _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
            );
            let _ = writeln!(src, "            }}");
        }
        let _ = writeln!(
            src,
            "                _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
        );
        let _ = writeln!(src, "            }}");
    }
    let _ = writeln!(src, "        }}");
    let _ = writeln!(
        src,
        "        if until.is_some() {{ return Err(ParseError::new(\"truncated group\")); }}"
    );
    let _ = writeln!(src, "        if enforce {{ self.check_required()?; }}");
    let _ = writeln!(src, "        Ok(())");
    let _ = writeln!(src, "    }}");
    if split_heavy {
        let _ = writeln!(src, "    #[inline(never)]");
        let _ = writeln!(
            src,
            "    fn merge_heavy(&mut self, n: u32, w: u32, data: &[u8], wire: &mut Option<pbrs::rt::Wire>, pos: &mut usize, depth: u32) -> Result<(), ParseError> {{"
        );
        let _ = writeln!(src, "        match n {{");
        for f in &heavies {
            let _ = writeln!(src, "            {} => match w {{", f.number);
            emit_merge_arm(src, desc, f);
            let _ = writeln!(
                src,
                "                _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
            );
            let _ = writeln!(src, "            }}");
        }
        let _ = writeln!(
            src,
            "            _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
        );
        let _ = writeln!(src, "        }}");
        let _ = writeln!(src, "        Ok(())");
        let _ = writeln!(src, "    }}");
    }

    let _ = writeln!(
        src,
        "    fn validate_inner(wire: &pbrs::rt::Wire, pos: &mut usize, depth: u32) -> Result<(), ParseError> {{ Self::validate_until(wire, pos, depth, None) }}"
    );
    let _ = writeln!(
        src,
        "    fn validate_until(wire: &pbrs::rt::Wire, pos: &mut usize, depth: u32, until: Option<u32>) -> Result<(), ParseError> {{"
    );
    let _ = writeln!(
        src,
        "        if depth > pbrs::RECURSION_LIMIT {{ return Err(ParseError::new(\"recursion limit exceeded\")); }}"
    );
    let _ = writeln!(src, "        let data = wire.as_slice();");
    if !required.is_empty() {
        let _ = writeln!(src, "        let mut seen = 0u64;");
    }
    let _ = writeln!(src, "        while *pos < data.len() {{");
    let _ = writeln!(
        src,
        "            let (n, w) = pbrs::rt::decode_tag(data, pos)?;"
    );
    let _ = writeln!(src, "            if let Some(g) = until {{ if w == pbrs::rt::WIRE_EGROUP {{ if n != g {{ return Err(ParseError::new(\"mismatched end-group\")); }} return Ok(()); }} }}");
    let _ = writeln!(src, "            match n {{");
    for f in desc.fields.values() {
        let bit = required.iter().position(|r| r.number == f.number);
        let _ = writeln!(src, "            {} => match w {{", f.number);
        emit_validate_arm(src, f, bit);
        let _ = writeln!(
            src,
            "                _ => pbrs::rt::skip_field(data, pos, w)?,"
        );
        let _ = writeln!(src, "            }}");
    }
    let _ = writeln!(
        src,
        "                _ => pbrs::rt::skip_field(data, pos, w)?,"
    );
    let _ = writeln!(src, "            }}");
    let _ = writeln!(src, "        }}");
    let _ = writeln!(
        src,
        "        if until.is_some() {{ return Err(ParseError::new(\"truncated group\")); }}"
    );
    if !required.is_empty() {
        let all = (1u64 << required.len()) - 1;
        let _ = writeln!(
            src,
            "        if seen != {all} {{ return Err(ParseError::new(\"missing required field\")); }}"
        );
    }
    let _ = writeln!(src, "        Ok(())");
    let _ = writeln!(src, "    }}");

    let _ = writeln!(src, "    fn compute_size(&self) -> u64 {{");
    let _ = writeln!(
        src,
        "        if let Some(n) = self.cached_size.get() {{ return n; }}"
    );
    let _ = writeln!(src, "        let mut n = self.unknown.encoded_len();");
    if desc.message_set_wire_format {
        emit_message_set_size(src, desc);
    } else {
        for f in desc.fields.values().filter(|f| stored_hot(desc, f)) {
            emit_size(src, f, "self");
        }
        if uses_cold_storage(desc) {
            let _ = writeln!(src, "        if let Some(c) = self.cold.as_deref() {{");
            for f in desc.fields.values().filter(|f| stored_cold(desc, f)) {
                emit_size(src, f, "c");
            }
            let _ = writeln!(src, "        }}");
        }
    }
    let _ = writeln!(src, "        self.cached_size.set(n);");
    let _ = writeln!(src, "        n");
    let _ = writeln!(src, "    }}");

    let _ = writeln!(
        src,
        "    fn write_to(&self, out: &mut impl pbrs::rt::WireOut) {{"
    );
    if desc.message_set_wire_format {
        emit_message_set_write(src, desc);
    } else {
        for f in desc.fields.values().filter(|f| stored_hot(desc, f)) {
            emit_write(src, f, "self");
        }
        if uses_cold_storage(desc) {
            let _ = writeln!(src, "        if let Some(c) = self.cold.as_deref() {{");
            for f in desc.fields.values().filter(|f| stored_cold(desc, f)) {
                emit_write(src, f, "c");
            }
            let _ = writeln!(src, "        }}");
        }
    }
    let _ = writeln!(src, "        self.unknown.encode(out);");
    let _ = writeln!(src, "    }}");
}

fn emit_message_set_merge(src: &mut String, desc: &MessageDescriptor) {
    let _ = writeln!(
        src,
        "            1 => match w {{ pbrs::rt::WIRE_SGROUP | pbrs::rt::WIRE_LEN => {{"
    );
    let _ = writeln!(
        src,
        "                    let mut type_id = 0u32; let mut payload: Vec<u8> = Vec::new();"
    );
    let _ = writeln!(src, "                    if w == pbrs::rt::WIRE_LEN {{ let inner = pbrs::rt::read_len_bytes(data, pos)?; let mut p = 0; while p < inner.len() {{ let (n, ww) = pbrs::rt::decode_tag(inner, &mut p)?; match (n, ww) {{ (2, pbrs::rt::WIRE_VARINT) => type_id = pbrs::rt::decode_varint(inner, &mut p)? as u32, (3, pbrs::rt::WIRE_LEN) => payload = pbrs::rt::read_len_bytes(inner, &mut p)?.to_vec(), _ => pbrs::rt::skip_field(inner, &mut p, ww)?, }} }} }} else {{ loop {{ let (n, ww) = pbrs::rt::decode_tag(data, pos)?; if ww == pbrs::rt::WIRE_EGROUP && n == 1 {{ break; }} match (n, ww) {{ (2, pbrs::rt::WIRE_VARINT) => type_id = pbrs::rt::decode_varint(data, pos)? as u32, (3, pbrs::rt::WIRE_LEN) => payload = pbrs::rt::read_len_bytes(data, pos)?.to_vec(), _ => pbrs::rt::skip_field(data, pos, ww)?, }} }} }}");
    let _ = writeln!(src, "                    match type_id {{");
    for f in desc.fields.values() {
        let id = field_id(f);
        let t = scalar_type(f);
        let num = f.number;
        if is_lazy_msg(f) {
            let _ = writeln!(src, "                        {num} => {{ if self.{id}.is_some() {{ self.{id}.get_or_insert().merge_bytes(&payload, depth + 1)?; }} else {{ let mut inner = {t}::default(); inner.merge_bytes(&payload, depth + 1)?; self.{id} = pbrs::rt::LazyMsg::from_owned(inner); }} }}");
        } else {
            let _ = writeln!(src, "                        {num} => {{ match &mut self.{id} {{ Some(existing) => existing.merge_bytes(&payload, depth + 1)?, None => {{ let mut inner = {t}::default(); inner.merge_bytes(&payload, depth + 1)?; self.{id} = Some(Box::new(inner)); }} }} }}");
        }
    }
    let _ = writeln!(src, "                        _ => {{ let mut u = pbrs::UnknownFields::default(); u.fields.push(pbrs::rt::UnknownField::Varint {{ number: 2, value: u64::from(type_id) }}); u.fields.push(pbrs::rt::UnknownField::LengthDelimited {{ number: 3, value: payload }}); self.unknown.fields.push(pbrs::rt::UnknownField::Group {{ number: 1, fields: u }}); }}");
    let _ = writeln!(src, "                    }}");
    let _ = writeln!(src, "                }}");
    let _ = writeln!(
        src,
        "                _ => self.unknown.fields.push(pbrs::rt::capture_unknown(data, pos, n, w)?),"
    );
    let _ = writeln!(src, "            }}");
}

fn emit_message_set_size(src: &mut String, desc: &MessageDescriptor) {
    for f in desc.fields.values() {
        let id = field_id(f);
        let num = f.number;
        let _ = writeln!(src, "        if let Some(m) = self.{id}.as_deref() {{ let inner = m.compute_size(); let item = pbrs::rt::tag_len(2, pbrs::rt::WIRE_VARINT) + pbrs::rt::varint_len({num} as u64) + pbrs::rt::key_len_value_len(3, inner); n += pbrs::rt::tag_len(1, pbrs::rt::WIRE_SGROUP) + item + pbrs::rt::tag_len(1, pbrs::rt::WIRE_EGROUP); }}");
    }
}

fn emit_message_set_write(src: &mut String, desc: &MessageDescriptor) {
    for f in desc.fields.values() {
        let id = field_id(f);
        let num = f.number;
        let _ = writeln!(src, "        if let Some(m) = self.{id}.as_deref() {{ pbrs::rt::encode_tag(out, 1, pbrs::rt::WIRE_SGROUP); pbrs::rt::encode_tag(out, 2, pbrs::rt::WIRE_VARINT); pbrs::rt::encode_varint(out, {num} as u64); pbrs::rt::encode_len_header(out, 3, m.compute_size()); m.write_to(out); pbrs::rt::encode_tag(out, 1, pbrs::rt::WIRE_EGROUP); }}");
    }
}

fn read_scalar_expr(ty: FieldType, buf: &str, pos: &str) -> String {
    match ty {
        FieldType::Double => format!("f64::from_bits(pbrs::rt::read_fixed64({buf}, {pos})?)"),
        FieldType::Float => format!("f32::from_bits(pbrs::rt::read_fixed32({buf}, {pos})?)"),
        FieldType::Fixed64 => format!("pbrs::rt::read_fixed64({buf}, {pos})?"),
        FieldType::Sfixed64 => format!("pbrs::rt::read_fixed64({buf}, {pos})? as i64"),
        FieldType::Fixed32 => format!("pbrs::rt::read_fixed32({buf}, {pos})?"),
        FieldType::Sfixed32 => format!("pbrs::rt::read_fixed32({buf}, {pos})? as i32"),
        FieldType::Sint32 => {
            format!("pbrs::rt::decode_zigzag32(pbrs::rt::decode_varint({buf}, {pos})?)")
        }
        FieldType::Sint64 => {
            format!("pbrs::rt::decode_zigzag64(pbrs::rt::decode_varint({buf}, {pos})?)")
        }
        FieldType::Bool => format!("pbrs::rt::decode_varint({buf}, {pos})? != 0"),
        FieldType::Int64 => format!("pbrs::rt::decode_varint({buf}, {pos})? as i64"),
        FieldType::Uint64 => format!("pbrs::rt::decode_varint({buf}, {pos})?"),
        FieldType::Uint32 => format!("pbrs::rt::decode_varint({buf}, {pos})? as u32"),
        _ => format!("pbrs::rt::decode_varint({buf}, {pos})? as i32"),
    }
}

fn emit_validate_arm(src: &mut String, f: &FieldDescriptor, req_bit: Option<usize>) {
    let num = f.number;
    let mark = if let Some(b) = req_bit {
        format!(" seen |= 1 << {b};")
    } else {
        String::new()
    };
    if f.is_map {
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let mut ip = 0; let w = wire.window(s, e); let d = w.as_slice(); while ip < d.len() {{ let (_, ww) = pbrs::rt::decode_tag(d, &mut ip)?; pbrs::rt::skip_field(d, &mut ip, ww)?; }}{mark} }}");
        return;
    }
    if f.cardinality == Cardinality::Repeated {
        if f.field_type == FieldType::String {
            let utf = if f.utf8_validate {
                "pbrs::rt::require_utf8(&data[s..e])?;"
            } else {
                ""
            };
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {utf}{mark} }}");
        } else if f.field_type == FieldType::Bytes {
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ pbrs::rt::read_len_span(data, pos)?;{mark} }}");
        } else if f.field_type == FieldType::Message {
            let t = scalar_type(f);
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let mut ip = 0; {t}::validate_inner(&wire.window(s, e), &mut ip, depth + 1)?;{mark} }}");
        } else if f.field_type == FieldType::Group || f.delimited {
            let t = scalar_type(f);
            let _ = writeln!(src, "                pbrs::rt::WIRE_SGROUP => {{ {t}::validate_until(wire, pos, depth + 1, Some({num}))?;{mark} }}");
        } else if f.field_type.is_packable() {
            let packed_ty = packed_storage_ty(f);
            let unpacked = read_scalar_expr(f.field_type, "data", "pos");
            let packed_wire = wire_const(f.field_type);
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {packed_ty}::validate_bytes(&data[s..e])?;{mark} }}");
            let _ = writeln!(
                src,
                "                {packed_wire} => {{ let _ = {unpacked};{mark} }}"
            );
        } else {
            let unpacked = read_scalar_expr(f.field_type, "data", "pos");
            let w = wire_const(f.field_type);
            let _ = writeln!(
                src,
                "                {w} => {{ let _ = {unpacked};{mark} }}"
            );
        }
        return;
    }
    if f.field_type == FieldType::Message {
        let t = scalar_type(f);
        if f.field_type == FieldType::Group || f.delimited {
            let _ = writeln!(src, "                pbrs::rt::WIRE_SGROUP => {{ {t}::validate_until(wire, pos, depth + 1, Some({num}))?;{mark} }}");
        } else {
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let mut ip = 0; {t}::validate_inner(&wire.window(s, e), &mut ip, depth + 1)?;{mark} }}");
        }
        return;
    }
    if f.field_type == FieldType::Group || f.delimited {
        let t = scalar_type(f);
        let _ = writeln!(src, "                pbrs::rt::WIRE_SGROUP => {{ {t}::validate_until(wire, pos, depth + 1, Some({num}))?;{mark} }}");
        return;
    }
    if f.field_type == FieldType::String {
        let utf = if f.utf8_validate {
            "pbrs::rt::require_utf8(&data[s..e])?;"
        } else {
            ""
        };
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {utf}{mark} }}");
        return;
    }
    if f.field_type == FieldType::Bytes {
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ pbrs::rt::read_len_span(data, pos)?;{mark} }}");
        return;
    }
    let expr = read_scalar_expr(f.field_type, "data", "pos");
    let w = wire_const(f.field_type);
    let _ = writeln!(src, "                {w} => {{ let _ = {expr};{mark} }}");
}

fn lazy_str_from_parse(f: &FieldDescriptor) -> &'static str {
    if f.utf8_validate {
        "pbrs::rt::LazyStr::from_parse_span(wire, data, s, e)?"
    } else {
        "pbrs::rt::LazyStr::from_parse_span_unchecked(wire, data, s, e)"
    }
}

/// Same-tag run for repeated length-delimited items (strings/bytes).
/// Reserve from remaining bytes so `tags_32` does not grow the Vec 5×.
fn emit_repeated_len_run(src: &mut String, num: u32, st: &str, push: &str) {
    let _ = writeln!(
        src,
        "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let rest = data.len().saturating_sub(e); if rest > 2 {{ {st}.reserve(1 + rest / (e - s + 2).max(1)); }} {st}.push({push}); while *pos < data.len() {{ let save = *pos; match pbrs::rt::decode_tag(data, pos) {{ Ok((n2, w2)) if n2 == {num} && w2 == pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {st}.push({push}); }} Ok(_) => {{ *pos = save; break; }} Err(e) => return Err(e), }} }} }}"
    );
}

fn emit_merge_arm(src: &mut String, desc: &MessageDescriptor, f: &FieldDescriptor) {
    let st = store_mut(desc, f);
    let num = f.number;
    if f.is_map {
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{");
        let _ = writeln!(
            src,
            "                    let (s, e) = pbrs::rt::read_len_span(data, pos)?;"
        );
        let _ = writeln!(
            src,
            "                    let (kk, vv) = decode_map_entry_{}_{}_{num}(&pbrs::rt::Wire::ensure(wire, data).window(s, e), depth + 1)?;",
            rust_ident(&desc.full_name),
            field_id(f).replace("r#", "")
        );
        let _ = writeln!(src, "                    {st}.push_entry(kk, vv);");
        let _ = writeln!(src, "                }}");
        return;
    }
    if f.cardinality == Cardinality::Repeated {
        if f.field_type == FieldType::String {
            emit_repeated_len_run(src, num, &st, lazy_str_from_parse(f));
        } else if f.field_type == FieldType::Bytes {
            emit_repeated_len_run(
                src,
                num,
                &st,
                "pbrs::rt::LazyBytes::from_wire(pbrs::rt::Wire::ensure(wire, data).window(s, e))",
            );
        } else if f.field_type == FieldType::Message || f.field_type == FieldType::Group {
            let t = scalar_type(f);
            if f.field_type == FieldType::Group || f.delimited {
                let _ = writeln!(src, "                pbrs::rt::WIRE_SGROUP => {{ let mut inner = {t}::default(); inner.merge_group(data, wire, pos, {num}, depth + 1)?; {st}.push(inner); }}");
            } else {
                let _ = writeln!(
                    src,
                    "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let rest = data.len().saturating_sub(e); if rest > 2 {{ {st}.reserve(1 + rest / (e - s + 4).max(1)); }} let mut inner = {t}::default(); let mut ip = 0; let mut sw = None; inner.merge_inner(&data[s..e], &mut sw, &mut ip, depth + 1, true, None)?; {st}.push(inner); while *pos < data.len() {{ let save = *pos; match pbrs::rt::decode_tag(data, pos) {{ Ok((n2, w2)) if n2 == {num} && w2 == pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; let mut inner = {t}::default(); let mut ip = 0; let mut sw = None; inner.merge_inner(&data[s..e], &mut sw, &mut ip, depth + 1, true, None)?; {st}.push(inner); }} Ok(_) => {{ *pos = save; break; }} Err(e) => return Err(e), }} }} }}"
                );
            }
        } else if f.field_type.is_packable() {
            let unpacked = read_scalar_expr(f.field_type, "data", "pos");
            let packed_wire = wire_const(f.field_type);
            if f.packed {
                if is_memcpy_packed(f) {
                    // Payload-only Arc. Do not Arc the parent message and do
                    // not eager-decode the Vec on parse.
                    let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {st}.append_wire(pbrs::rt::Wire::from_slice(&data[s..e]))?; }}");
                } else {
                    let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let (s, e) = pbrs::rt::read_len_span(data, pos)?; {st}.append_wire(pbrs::rt::Wire::ensure(wire, data).window(s, e))?; }}");
                }
            } else {
                let expr = read_scalar_expr(f.field_type, "p", "&mut i");
                let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{ let p = pbrs::rt::read_len_bytes(data, pos)?; let mut i = 0; while i < p.len() {{ {st}.push({expr}); }} }}");
            }
            let _ = writeln!(
                src,
                "                {packed_wire} => {{ {st}.push({unpacked}); let rest = data.len().saturating_sub(*pos); if rest > 2 {{ {st}.reserve(rest / 3); }} while *pos < data.len() {{ let save = *pos; match pbrs::rt::decode_tag(data, pos) {{ Ok((n2, w2)) if n2 == {num} && w2 == {packed_wire} => {st}.push({unpacked}), Ok(_) => {{ *pos = save; break; }} Err(e) => return Err(e), }} }} }}"
            );
        } else {
            let unpacked = read_scalar_expr(f.field_type, "data", "pos");
            let w = wire_const(f.field_type);
            let _ = writeln!(src, "                {w} => {st}.push({unpacked}),");
        }
        return;
    }
    if f.field_type == FieldType::Message || f.field_type == FieldType::Group {
        let t = scalar_type(f);
        if f.field_type == FieldType::Group || f.delimited {
            let _ = writeln!(src, "                pbrs::rt::WIRE_SGROUP => {{");
            emit_oneof_clear(src, desc, f);
            let _ = writeln!(src, "                    match &mut {st} {{ Some(existing) => existing.merge_group(data, wire, pos, {num}, depth + 1)?, None => {{ let mut inner = {t}::default(); inner.merge_group(data, wire, pos, {num}, depth + 1)?; {st} = Some(Box::new(inner)); }} }}");
            let _ = writeln!(src, "                    }}");
        } else {
            let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{");
            emit_oneof_clear(src, desc, f);
            let _ = writeln!(
                src,
                "                    let (s, e) = pbrs::rt::read_len_span(data, pos)?;"
            );
            if is_lazy_msg(f) {
                let _ = writeln!(src, "                    if {st}.is_some() {{ let mut ip = 0; let mut sw = None; {st}.get_or_insert().merge_inner(&data[s..e], &mut sw, &mut ip, depth + 1, true, None)?; }} else {{ let mut ip = 0; {t}::validate_inner(&pbrs::rt::Wire::ensure(wire, data).window(s, e), &mut ip, depth + 1)?; {st} = pbrs::rt::LazyMsg::from_wire(pbrs::rt::Wire::ensure(wire, data).window(s, e)); }}");
            } else {
                let _ = writeln!(src, "                    match &mut {st} {{ Some(existing) => {{ let mut ip = 0; let mut sw = None; existing.merge_inner(&data[s..e], &mut sw, &mut ip, depth + 1, true, None)?; }} None => {{ let mut inner = {t}::default(); let mut ip = 0; let mut sw = None; inner.merge_inner(&data[s..e], &mut sw, &mut ip, depth + 1, true, None)?; {st} = Some(Box::new(inner)); }} }}");
            }
            let _ = writeln!(src, "                    }}");
        }
        return;
    }
    if f.field_type == FieldType::String {
        let parse = lazy_str_from_parse(f);
        let assign = if is_option(f) {
            format!("{st} = Some(Box::new({parse}))")
        } else {
            format!("{st} = {parse}")
        };
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{");
        emit_oneof_clear(src, desc, f);
        let _ = writeln!(
            src,
            "                    let (s, e) = pbrs::rt::read_len_span(data, pos)?; {assign};"
        );
        let _ = writeln!(src, "                    }}");
        return;
    }
    if f.field_type == FieldType::Bytes {
        let assign = if is_option(f) {
            format!("{st} = Some(Box::new(pbrs::rt::LazyBytes::from_wire(pbrs::rt::Wire::ensure(wire, data).window(s, e))))")
        } else {
            format!("{st} = pbrs::rt::LazyBytes::from_wire(pbrs::rt::Wire::ensure(wire, data).window(s, e))")
        };
        let _ = writeln!(src, "                pbrs::rt::WIRE_LEN => {{");
        emit_oneof_clear(src, desc, f);
        let _ = writeln!(
            src,
            "                    let (s, e) = pbrs::rt::read_len_span(data, pos)?; {assign};"
        );
        let _ = writeln!(src, "                    }}");
        return;
    }
    let expr = read_scalar_expr(f.field_type, "data", "pos");
    let w = wire_const(f.field_type);
    let assign = if is_option(f) && f.field_type == FieldType::Bool {
        format!("{st} = pbrs::rt::OptBool::some({expr})")
    } else if is_option(f) {
        format!("{st} = Some({expr})")
    } else {
        format!("{st} = {expr}")
    };
    let _ = writeln!(src, "                {w} => {{");
    emit_oneof_clear(src, desc, f);
    let _ = writeln!(src, "                    {assign};");
    let _ = writeln!(src, "                    }}");
}

fn packed_len_expr(v: &str, ty: FieldType) -> String {
    match ty {
        FieldType::Fixed64 | FieldType::Sfixed64 | FieldType::Double => "8".into(),
        FieldType::Fixed32 | FieldType::Sfixed32 | FieldType::Float => "4".into(),
        FieldType::Sint32 => {
            format!("pbrs::rt::varint_len(pbrs::rt::encode_zigzag32({v}))")
        }
        FieldType::Sint64 => {
            format!("pbrs::rt::varint_len(pbrs::rt::encode_zigzag64({v}))")
        }
        FieldType::Bool => format!("pbrs::rt::varint_len(u64::from({v}))"),
        _ => format!("pbrs::rt::varint_len(({v}) as u64)"),
    }
}

fn write_packed_stmt(out: &str, v: &str, ty: FieldType) -> String {
    match ty {
        FieldType::Double => format!("({out}).extend_from_slice(&({v}).to_bits().to_le_bytes())"),
        FieldType::Float => format!("({out}).extend_from_slice(&({v}).to_bits().to_le_bytes())"),
        FieldType::Fixed64 => format!("({out}).extend_from_slice(&({v}).to_le_bytes())"),
        FieldType::Sfixed64 => format!("({out}).extend_from_slice(&(({v}) as u64).to_le_bytes())"),
        FieldType::Fixed32 => format!("({out}).extend_from_slice(&({v}).to_le_bytes())"),
        FieldType::Sfixed32 => format!("({out}).extend_from_slice(&(({v}) as u32).to_le_bytes())"),
        FieldType::Sint32 => {
            format!("pbrs::rt::encode_varint({out}, pbrs::rt::encode_zigzag32({v}))")
        }
        FieldType::Sint64 => {
            format!("pbrs::rt::encode_varint({out}, pbrs::rt::encode_zigzag64({v}))")
        }
        FieldType::Bool => format!("pbrs::rt::encode_varint({out}, u64::from({v}))"),
        _ => format!("pbrs::rt::encode_varint({out}, {v} as u64)"),
    }
}

fn emit_size(src: &mut String, f: &FieldDescriptor, p: &str) {
    let id = field_id(f);
    let fld = format!("{p}.{id}");
    let num = f.number;
    if f.is_map {
        let _ = writeln!(src, "        if !{fld}.is_empty() {{");
        let _ = writeln!(src, "        for (k, v) in {fld}.pairs() {{");
        let key_sz = map_key_size(map_key_ty(f), "k");
        let val_sz = map_val_size(map_val_ty(f), "v");
        let _ = writeln!(src, "            let inner = {key_sz} + {val_sz};");
        let _ = writeln!(
            src,
            "            n += pbrs::rt::key_len_value_len({num}, inner);"
        );
        let _ = writeln!(src, "        }}");
        let _ = writeln!(src, "        }}");
        return;
    }
    if f.cardinality == Cardinality::Repeated {
        if f.field_type == FieldType::String || f.field_type == FieldType::Bytes {
            let _ = writeln!(src, "        for t in {fld}.iter() {{ n += pbrs::rt::key_len_value_len({num}, t.as_bytes().len() as u64); }}");
        } else if f.field_type == FieldType::Group || f.delimited {
            let _ = writeln!(src, "        for t in {fld}.iter() {{ n += pbrs::rt::tag_len({num}, pbrs::rt::WIRE_SGROUP) + t.compute_size() + pbrs::rt::tag_len({num}, pbrs::rt::WIRE_EGROUP); }}");
        } else if f.field_type == FieldType::Message {
            let _ = writeln!(src, "        for t in {fld}.iter() {{ n += pbrs::rt::key_len_value_len({num}, t.compute_size()); }}");
        } else if f.packed && f.field_type.is_packable() {
            let plen = packed_len_expr("*t", f.field_type);
            let _ = writeln!(src, "        if let Some(p) = {fld}.packed_bytes() {{ n += pbrs::rt::key_len_value_len({num}, p.len() as u64); }} else if !{fld}.is_empty() {{ let mut payload = 0u64; for t in {fld}.iter() {{ payload += {plen}; }} n += pbrs::rt::key_len_value_len({num}, payload); }}");
        } else {
            let plen = packed_len_expr("*t", f.field_type);
            let w = wire_const(f.field_type);
            let _ = writeln!(
                src,
                "        for t in {fld}.iter() {{ n += pbrs::rt::tag_len({num}, {w}) + {plen}; }}"
            );
        }
        return;
    }
    if f.field_type == FieldType::Group || f.delimited {
        let _ = writeln!(src, "        if let Some(m) = &{fld} {{ n += pbrs::rt::tag_len({num}, pbrs::rt::WIRE_SGROUP) + m.compute_size() + pbrs::rt::tag_len({num}, pbrs::rt::WIRE_EGROUP); }}");
        return;
    }
    if f.field_type == FieldType::Message {
        if is_lazy_msg(f) {
            let _ = writeln!(src, "        if let Some(p) = {fld}.wire_bytes() {{ n += pbrs::rt::key_len_value_len({num}, p.len() as u64); }} else if let Some(m) = {fld}.as_deref() {{ n += pbrs::rt::key_len_value_len({num}, m.compute_size()); }}");
        } else {
            let _ = writeln!(src, "        if let Some(m) = &{fld} {{ n += pbrs::rt::key_len_value_len({num}, m.compute_size()); }}");
        }
        return;
    }
    if f.field_type == FieldType::String || f.field_type == FieldType::Bytes {
        if is_option(f) {
            let _ = writeln!(src, "        if let Some(s) = &{fld} {{ n += pbrs::rt::key_len_value_len({num}, s.as_bytes().len() as u64); }}");
        } else {
            let _ = writeln!(src, "        if !{fld}.is_empty() {{ n += pbrs::rt::key_len_value_len({num}, {fld}.as_bytes().len() as u64); }}");
        }
        return;
    }
    let sz = packed_len_expr("v", f.field_type);
    let w = wire_const(f.field_type);
    if is_option(f) && f.field_type == FieldType::Bool {
        let _ = writeln!(
            src,
            "        if let Some(v) = {fld}.get() {{ n += pbrs::rt::tag_len({num}, {w}) + {sz}; }}"
        );
    } else if is_option(f) {
        let _ = writeln!(
            src,
            "        if let Some(v) = {fld} {{ n += pbrs::rt::tag_len({num}, {w}) + {sz}; }}"
        );
    } else {
        let pred = implicit_present(&fld, f.field_type);
        let sz2 = packed_len_expr(&fld, f.field_type);
        let _ = writeln!(
            src,
            "        if {pred} {{ n += pbrs::rt::tag_len({num}, {w}) + {sz2}; }}"
        );
    }
}

