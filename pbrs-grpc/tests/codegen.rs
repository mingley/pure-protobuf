//! The code generator, exercised the way a user's crate exercises it.
//!
//! `tests/proto/kv.proto` is compiled by `build.rs` with `Stubs::Kernel` and
//! included here. An integration test is a separate crate, so the generated
//! `::pbrs_grpc::...` paths have to resolve through an ordinary dependency
//! rather than through the `extern crate self as pbrs_grpc` alias the library
//! uses internally. If that ever broke, users would find out and this crate
//! would not; now this file does.
//!
//! All four RPC shapes are driven end to end over loopback.

