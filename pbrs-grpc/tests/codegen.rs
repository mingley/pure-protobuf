use kv::{
    Entry, Event, GetRequest, GetResponse, Kind, PutSummary, Store, StoreClient, StoreServer,
    WatchRequest,
};

fn entry(key: &str, value: &[u8]) -> Entry {
    let mut e = Entry::new();
    e.set_key(key);
    e.set_value(value.to_vec());
    e
}

fn event(kind: Kind, key: &str) -> Event {
    let mut ev = Event::new();
    ev.set_kind(kind);
    ev.set_entry(entry(key, b""));
    ev
}

fn key_of(e: &Entry) -> String {
    e.key().to_str().unwrap_or_default().to_owned()
}

/// A memory store that answers all four shapes.
struct MemStore;

impl Store for MemStore {
    async fn get(&self, request: Request<GetRequest>) -> Result<Response<GetResponse>, Status> {
        let key = request
            .get_ref()
            .key()
            .to_str()
            .unwrap_or_default()
            .to_owned();
        if key.is_empty() {
            return Err(Status::invalid_argument("empty key"));
        }
        let mut resp = GetResponse::new();
        resp.set_found(true);
        resp.set_entry(entry(&key, b"value"));
        Ok(Response::new(resp))
    }

    async fn put_all(
        &self,
        request: Request<Streaming<Entry>>,
    ) -> Result<Response<PutSummary>, Status> {
        let mut stream = request.into_inner();
        let mut summary = PutSummary::new();
        let mut entries = 0i64;
        let mut bytes = 0i64;
        while let Some(e) = stream.message().await? {
            entries += 1;
            bytes += e.value().len() as i64;
            summary.keys_mut().push(pbrs::ProtoString::from(key_of(&e)));
        }
        summary.set_entries(entries);
        summary.set_bytes(bytes);
        Ok(Response::new(summary))
    }

    async fn watch(
        &self,
        request: Request<WatchRequest>,
    ) -> Result<Response<Streaming<Event>>, Status> {
        let prefixes: Vec<String> = request
            .get_ref()
            .prefixes()
            .iter()
            .map(|p| p.to_str().unwrap_or_default().to_owned())
            .collect();
        let (tx, stream) = Streaming::channel(8);
        drop(tokio::spawn(async move {
            for prefix in prefixes {
                if tx.send(event(Kind::Put, &prefix)).await.is_err() {
                    return;
                }
            }
        }));
        Ok(Response::new(stream))
    }

    async fn sync(
        &self,
        request: Request<Streaming<Entry>>,
    ) -> Result<Response<Streaming<Event>>, Status> {
        let mut inbound = request.into_inner();
        let (tx, stream) = Streaming::channel(8);
        drop(tokio::spawn(async move {
            loop {
                match inbound.message().await {
                    Ok(Some(e)) => {
                        if tx.send(event(Kind::Delete, &key_of(&e))).await.is_err() {
                            return;
                        }
                    }
                    Ok(None) => break,
                    Err(status) => {
                        tx.fail(status).await;
                        break;
                    }
                }
            }
        }));
        Ok(Response::new(stream))
    }
}

