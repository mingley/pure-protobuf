/// Exactly what a user writes: include the generated file and use the names.
mod kv {
    #![allow(missing_docs, unused, reason = "generated by protoc-gen-pbrs")]
    include!(concat!(env!("OUT_DIR"), "/kv.rs"));
}

use kv::{
    Entry, Event, GetRequest, GetResponse, Kind, PutSummary, Store, StoreClient, StoreServer,
    WatchRequest,
};

fn entry(key: &str, value: &[u8]) -> Entry {
    let mut e = Entry::new();
    e.set_key(key);
    e.set_value(value.to_vec());
    e
}

fn event(kind: Kind, key: &str) -> Event {
    let mut ev = Event::new();
    ev.set_kind(kind);
    ev.set_entry(entry(key, b""));
    ev
}

fn key_of(e: &Entry) -> String {
    e.key().to_str().unwrap_or_default().to_owned()
}

/// A memory store that answers all four shapes.
struct MemStore;

impl Store for MemStore {
    async fn get(&self, request: Request<GetRequest>) -> Result<Response<GetResponse>, Status> {
        let key = request
            .get_ref()
            .key()
            .to_str()
            .unwrap_or_default()
            .to_owned();
        if key.is_empty() {
            return Err(Status::invalid_argument("empty key"));
        }
        let mut resp = GetResponse::new();
        resp.set_found(true);
        resp.set_entry(entry(&key, b"value"));
        Ok(Response::new(resp))
    }

    async fn put_all(
        &self,
        request: Request<Streaming<Entry>>,
    ) -> Result<Response<PutSummary>, Status> {
        let mut stream = request.into_inner();
        let mut summary = PutSummary::new();
        let mut entries = 0i64;
        let mut bytes = 0i64;
        while let Some(e) = stream.message().await? {
            entries += 1;
            bytes += e.value().len() as i64;
            summary.keys_mut().push(pbrs::ProtoString::from(key_of(&e)));
        }
        summary.set_entries(entries);
        summary.set_bytes(bytes);
        Ok(Response::new(summary))
    }

    async fn watch(
        &self,
        request: Request<WatchRequest>,
    ) -> Result<Response<Streaming<Event>>, Status> {
        let prefixes: Vec<String> = request
            .get_ref()
            .prefixes()
            .iter()
            .map(|p| p.to_str().unwrap_or_default().to_owned())
            .collect();
        let (tx, stream) = Streaming::channel(8);
        drop(tokio::spawn(async move {
            for prefix in prefixes {
                if tx.send(event(Kind::Put, &prefix)).await.is_err() {
                    return;
                }
            }
        }));
        Ok(Response::new(stream))
    }

    async fn sync(
        &self,
        request: Request<Streaming<Entry>>,
    ) -> Result<Response<Streaming<Event>>, Status> {
        let mut inbound = request.into_inner();
        let (tx, stream) = Streaming::channel(8);
        drop(tokio::spawn(async move {
            while let Ok(Some(e)) = inbound.message().await {
                if tx.send(event(Kind::Delete, &key_of(&e))).await.is_err() {
                    return;
                }
            }
        }));
        Ok(Response::new(stream))
    }
}

async fn serve() -> (SocketAddr, tokio::task::JoinHandle<()>) {
    let listener = TcpListener::bind(SocketAddr::from(([127, 0, 0, 1], 0)))
        .await
        .expect("bind");
    let addr = listener.local_addr().expect("addr");
    let handle = tokio::spawn(async move {
        StoreServer::new(MemStore)
            .serve_listener(listener)
            .await
            .ok();
    });
    (addr, handle)
}

async fn client(addr: SocketAddr) -> StoreClient {
    for _ in 0..80 {
        if let Ok(client) = StoreClient::connect(addr).await {
            return client;
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    panic!("could not connect to {addr}");
}

#[tokio::test]
async fn generated_stubs_serve_all_four_shapes() {
    let (addr, server) = serve().await;
    let client = client(addr).await;

    // Unary.
    let mut get = GetRequest::new();
    get.set_key("alpha");
    let got = client.get(Request::new(get)).await.expect("unary");
    assert!(got.get_ref().found());
    assert_eq!(key_of(got.get_ref().entry()), "alpha");

    // Client-streaming.
    let (tx, call) = client.put_all(Request::new(()));
    for (key, value) in [("a", &b"11"[..]), ("b", &b"222"[..])] {
        tx.send(entry(key, value)).await.expect("send");
    }
    tx.close();
    let summary = call.await.expect("client-stream");
    assert_eq!(summary.get_ref().entries(), 2);
    assert_eq!(summary.get_ref().bytes(), 5);
    let keys: Vec<String> = summary
        .get_ref()
        .keys()
        .iter()
        .map(|k| k.to_str().unwrap_or_default().to_owned())
        .collect();
    assert_eq!(keys, ["a", "b"]);

    // Server-streaming.
    let mut watch = WatchRequest::new();
    for prefix in ["x", "y", "z"] {
        watch.prefixes_mut().push(pbrs::ProtoString::from(prefix));
    }
    let mut events = client
        .watch(Request::new(watch))
        .await
        .expect("server-stream")
        .into_inner();
    let mut seen = Vec::new();
    while let Some(ev) = events.message().await.expect("event") {
        assert_eq!(ev.kind(), Kind::Put);
        seen.push(key_of(ev.entry()));
    }
    assert_eq!(seen, ["x", "y", "z"]);

    // Bidirectional-streaming.
    let (tx, call) = client.sync(Request::new(()));
    let mut inbound = call.await.expect("bidi").into_inner();
    for key in ["p", "q"] {
        tx.send(entry(key, b"v")).await.expect("send");
        let ev = inbound.message().await.expect("event").expect("some");
        assert_eq!(ev.kind(), Kind::Delete);
        assert_eq!(key_of(ev.entry()), key);
    }
    tx.close();
    while inbound.message().await.expect("drain").is_some() {}

    server.abort();
}

