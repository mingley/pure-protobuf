async fn echo_store_every_shape(client: &StoreClient) {
    let mut get = GetRequest::new();
    get.set_key("alpha");
    let got = client.get(Request::new(get)).await.expect("unary");
    assert!(got.get_ref().found());
    assert_eq!(key_of(got.get_ref().entry()), "alpha");

    let (tx, call) = client.put_all(Request::new(()));
    for (key, value) in [("a", &b"11"[..]), ("b", &b"222"[..])] {
        tx.send(entry(key, value)).await.expect("send");
    }
    tx.close();
    let summary = call.await.expect("client-stream");
    assert_eq!(summary.get_ref().entries(), 2);
    assert_eq!(summary.get_ref().bytes(), 5);
    let keys: Vec<String> = summary
        .get_ref()
        .keys()
        .iter()
        .map(|k| k.to_str().unwrap_or_default().to_owned())
        .collect();
    assert_eq!(keys, ["a", "b"]);

    let mut watch = WatchRequest::new();
    for prefix in ["x", "y", "z"] {
        watch.prefixes_mut().push(pbrs::ProtoString::from(prefix));
    }
    let mut events = client
        .watch(Request::new(watch))
        .await
        .expect("server-stream")
        .into_inner();
    let mut seen = Vec::new();
    while let Some(ev) = events.message().await.expect("event") {
        assert_eq!(ev.kind(), Kind::Put);
        seen.push(key_of(ev.entry()));
    }
    assert_eq!(seen, ["x", "y", "z"]);

    let (tx, call) = client.sync(Request::new(()));
    let mut inbound = call.await.expect("bidi").into_inner();
    for key in ["p", "q"] {
        tx.send(entry(key, b"v")).await.expect("send");
        let ev = inbound.message().await.expect("event").expect("some");
        assert_eq!(ev.kind(), Kind::Delete);
        assert_eq!(key_of(ev.entry()), key);
    }
    tx.close();
    while inbound.message().await.expect("drain").is_some() {}
}

async fn gzip_store_every_shape(client: &StoreClient) {
    let mut get = GetRequest::new();
    get.set_key("alpha");
    let got = client.get(Request::new(get)).await.expect("unary");
    assert!(got.compressed(), "unary gzip");
    assert_eq!(got.encoding(), Some("gzip"), "{:?}", got.encoding());
    assert!(got.get_ref().found());
    assert_eq!(key_of(got.get_ref().entry()), "alpha");

    let (tx, call) = client.put_all(Request::new(()));
    assert!(tx.compress(), "put_all StreamSender must gzip");
    for (key, value) in [("a", &b"11"[..]), ("b", &b"222"[..])] {
        tx.send(entry(key, value)).await.expect("send");
    }
    tx.close();
    let summary = call.await.expect("client-stream");
    assert!(summary.compressed(), "put_all reply gzip");
    assert_eq!(summary.encoding(), Some("gzip"));
    assert_eq!(summary.get_ref().entries(), 2);
    assert_eq!(summary.get_ref().bytes(), 5);

    let mut watch = WatchRequest::new();
    for prefix in ["x", "y", "z"] {
        watch.prefixes_mut().push(pbrs::ProtoString::from(prefix));
    }
    let reply = client
        .watch(Request::new(watch))
        .await
        .expect("server-stream");
    assert_eq!(reply.encoding(), Some("gzip"), "watch encoding");
    let mut events = reply.into_inner();
    let framed = events.next_framed().await.expect("frame").expect("message");
    assert!(framed.compressed, "watch frames gzip");
    assert_eq!(framed.message.kind(), Kind::Put);
    let mut seen = vec![key_of(framed.message.entry())];
    while let Some(ev) = events.message().await.expect("event") {
        assert_eq!(ev.kind(), Kind::Put);
        seen.push(key_of(ev.entry()));
    }
    assert_eq!(seen, ["x", "y", "z"]);

    let (tx, call) = client.sync(Request::new(()));
    assert!(tx.compress(), "sync StreamSender must gzip");
    let reply = call.await.expect("bidi");
    assert_eq!(reply.encoding(), Some("gzip"), "sync encoding");
    let mut inbound = reply.into_inner();
    for key in ["p", "q"] {
        tx.send(entry(key, b"v")).await.expect("send");
        let framed = inbound.next_framed().await.expect("frame").expect("some");
        assert!(framed.compressed, "sync frames gzip");
        assert_eq!(framed.message.kind(), Kind::Delete);
        assert_eq!(key_of(framed.message.entry()), key);
    }
    tx.close();
    while inbound.message().await.expect("drain").is_some() {}
}

async fn assert_store_err_every_shape(client: &StoreClient, want: Code) {
    let mut get = GetRequest::new();
    get.set_key("intercepted");
    let err = client.get(Request::new(get)).await.expect_err("unary");
    assert_eq!(err.code(), want, "{err}");

    let mut watch = WatchRequest::new();
    watch.prefixes_mut().push(pbrs::ProtoString::from("x"));
    let err = client
        .watch(Request::new(watch))
        .await
        .expect_err("server-stream");
    assert_eq!(err.code(), want, "{err}");

    let (tx, call) = client.put_all(Request::new(()));
    let err = call.await.expect_err("client-stream");
    assert_eq!(err.code(), want, "{err}");
    drop(tx);

    let (tx, call) = client.sync(Request::new(()));
    let err = call.await.expect_err("bidi");
    assert_eq!(err.code(), want, "{err}");
    drop(tx);
}

fn fat_store_key() -> String {
    "k".repeat(64)
}

async fn assert_store_oversize_every_shape(client: &StoreClient) {
    let mut get = GetRequest::new();
    get.set_key(fat_store_key());
    let err = client.get(Request::new(get)).await.expect_err("unary");
    assert_eq!(err.code(), Code::ResourceExhausted, "{err}");

    let mut watch = WatchRequest::new();
    watch
        .prefixes_mut()
        .push(pbrs::ProtoString::from(fat_store_key()));
    match client.watch(Request::new(watch)).await {
        Err(err) => assert_eq!(err.code(), Code::ResourceExhausted, "{err}"),
        Ok(resp) => match resp.into_inner().message().await {
            Err(err) => assert_eq!(err.code(), Code::ResourceExhausted, "{err}"),
            Ok(_) => panic!("server-stream over the server cap must fail"),
        },
    }

    let (tx, call) = client.put_all(Request::new(()));
    tx.send(entry(&fat_store_key(), b"v")).await.expect("send");
    tx.close();
    let err = call.await.expect_err("client-stream over the server cap");
    assert_eq!(err.code(), Code::ResourceExhausted, "{err}");

    let (tx, call) = client.sync(Request::new(()));
    tx.send(entry(&fat_store_key(), b"v")).await.expect("send");
    tx.close();
    match call.await {
        Err(err) => assert_eq!(err.code(), Code::ResourceExhausted, "{err}"),
        Ok(resp) => match resp.into_inner().message().await {
            Err(err) => assert_eq!(err.code(), Code::ResourceExhausted, "{err}"),
            Ok(_) => panic!("bidi over the server cap must fail"),
        },
    }
}

fn stamp_outgoing_context(call: &mut Outgoing<'_>) -> Result<(), Status> {
    let path = call.path();
    call.metadata_mut().insert("x-path", path)?;
    let service = call.service();
    call.metadata_mut().set("x-service", service)?;
    let method = call.method();
    call.metadata_mut().set("x-method", method)?;
    let authority = call.authority();
    call.metadata_mut().insert("x-authority", authority)?;
    let scheme = call.scheme();
    call.metadata_mut().set("x-scheme", scheme)?;
    Ok(())
}

fn require_stamped_context(rpc: &mut pbrs_grpc::Rpc) -> Result<(), Status> {
    if rpc.metadata().get("x-path") != Some(rpc.path()) {
        return Err(Status::invalid_argument(format!(
            "x-path {:?} path {}",
            rpc.metadata().get("x-path"),
            rpc.path()
        )));
    }
    if rpc.metadata().get("x-service") != Some(rpc.service()) {
        return Err(Status::invalid_argument(format!(
            "x-service {:?} service {}",
            rpc.metadata().get("x-service"),
            rpc.service()
        )));
    }
    if rpc.metadata().get("x-method") != Some(rpc.method()) {
        return Err(Status::invalid_argument(format!(
            "x-method {:?} method {}",
            rpc.metadata().get("x-method"),
            rpc.method()
        )));
    }
    if rpc.metadata().get("x-authority") != rpc.authority() {
        return Err(Status::invalid_argument(format!(
            "x-authority {:?} authority {:?}",
            rpc.metadata().get("x-authority"),
            rpc.authority()
        )));
    }
    if rpc.metadata().get("x-scheme") != rpc.scheme() {
        return Err(Status::invalid_argument(format!(
            "x-scheme {:?} scheme {:?}",
            rpc.metadata().get("x-scheme"),
            rpc.scheme()
        )));
    }
    Ok(())
}

fn interceptor_blocked() -> Status {
    let mut info = pbrs_grpc::pb::ErrorInfo::new();
    info.set_reason("BLOCKED");
    info.set_domain("example.com");
    Status::with_error_details(
        Code::FailedPrecondition,
        "blocked locally",
        [pbrs_grpc::pb::Any::pack(&info).expect("pack")],
    )
    .expect("details")
}

fn assert_store_blocked(err: &Status) {
    assert_eq!(err.code(), Code::FailedPrecondition, "{err}");
    assert_eq!(err.message(), "blocked locally");
    let info = err
        .rpc()
        .expect("google.rpc.Status")
        .details()
        .get(0)
        .expect("one Any")
        .unpack::<pbrs_grpc::pb::ErrorInfo>()
        .expect("ErrorInfo");
    assert_eq!(info.reason().to_str().unwrap_or(""), "BLOCKED");
    assert_eq!(info.domain().to_str().unwrap_or(""), "example.com");
    let unpacked = err
        .error_details()
        .expect("ErrorDetails")
        .error_info
        .expect("ErrorInfo");
    assert_eq!(unpacked.reason().to_str().unwrap_or(""), "BLOCKED");
    assert_eq!(unpacked.domain().to_str().unwrap_or(""), "example.com");
}

async fn assert_store_blocked_every_shape(client: &StoreClient) {
    let mut get = GetRequest::new();
    get.set_key("intercepted");
    assert_store_blocked(&client.get(Request::new(get)).await.expect_err("unary"));

    let mut watch = WatchRequest::new();
    watch.prefixes_mut().push(pbrs::ProtoString::from("x"));
    match client.watch(Request::new(watch)).await {
        Err(err) => assert_store_blocked(&err),
        Ok(resp) => match resp.into_inner().message().await {
            Err(err) => assert_store_blocked(&err),
            Ok(_) => panic!("server-stream interceptor reject must fail"),
        },
    }

    let (tx, call) = client.put_all(Request::new(()));
    assert_store_blocked(&call.await.expect_err("client-stream"));
    drop(tx);

    let (tx, call) = client.sync(Request::new(()));
    assert_store_blocked(&call.await.expect_err("bidi"));
    drop(tx);
}

