    for key in ["p", "q"] {
        tx.send(entry(key, b"v")).await.expect("send");
        let ev = inbound.message().await.expect("event").expect("some");
        assert_eq!(ev.kind(), Kind::Delete);
        assert_eq!(key_of(ev.entry()), key);
    }
